// Tree view component for template structure
interface TreeItem {
  id: string;
  label: string;
  children?: TreeItem[];
}

interface TreeViewProps {
  data: TreeItem[];
  selectedId?: string;
  onSelect: (id: string) => void;
}

export const TreeView: React.FC<TreeViewProps> = ({ data, selectedId, onSelect }) => {
  const renderItem = (item: TreeItem, depth = 0) => (
    <div key={item.id} className="select-none">
      <div
        className={clsx(
          'flex items-center py-1 px-2 cursor-pointer hover:bg-accent rounded-sm',
          selectedId === item.id && 'bg-accent',
        )}
        style={{ paddingLeft: `${depth * 16 + 8}px` }}
        onClick={() => onSelect(item.id)}
      >
        <span className="text-sm">{item.label}</span>
      </div>
      {item.children?.map(child => renderItem(child, depth + 1))}
    </div>
  );

  return (
    <div className="w-full">
      {data.map(item => renderItem(item))}
    </div>
  );
};